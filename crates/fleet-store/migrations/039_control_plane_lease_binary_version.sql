-- 037: 리스를 쥔 인스턴스의 바이너리 버전을 함께 기록한다 (로드맵 #67 게이트 ⑤).
--
-- 게이트 ⑤의 "binary 버전 비호환" 절반은 지금까지 **생산자가 없어서** 미착수였다.
-- 정본이 적은 그대로다: 저장소 어디에도 바이너리 버전을 DB에 쓰는 코드가 없고
-- 이 테이블에 버전 컬럼도 없으므로, 술어만 넣으면 항상 참인 죽은 검사가 된다.
-- 이 마이그레이션이 그 생산자의 자리를 만든다.
--
-- ## 거절은 함께 넣지 않는다
--
-- 버전이 다르다고 기동을 막는 술어는 **롤링 업그레이드를 통째로 거절한다** —
-- 새 바이너리는 정의상 옛 Primary가 리스를 쥔 동안 올라오기 때문이다. 무엇을
-- "비호환"으로 볼지는 이 프로젝트가 아직 선언한 적 없는 계약이고(0.x에서 어느
-- 축이 깨지는 축인지, 같은 major면 섞여 돌아도 되는지), 그 계약 없이 술어를
-- 고르면 운영 절차를 코드가 임의로 정하는 셈이 된다. 그래서 이 증분은
-- **관측만** 만들고 강제는 계약이 정해질 때로 미룬다 — `#70` 게이트 3이
-- orphan을 막기 전에 먼저 보이게 만든 것과 같은 순서다.
--
-- ## NULL을 허용하는 이유
--
-- 이 컬럼을 쓰지 않는 옛 바이너리가 리스를 쥘 수 있고, 이 마이그레이션 이전에
-- 만들어진 행도 있다. NOT NULL로 만들면 그 둘이 곧바로 깨진다. 읽는 쪽은
-- "모른다"와 "다르다"를 구분해야 하므로 `Option`으로 받는다.
ALTER TABLE control_plane_lease
    ADD COLUMN binary_version TEXT;
