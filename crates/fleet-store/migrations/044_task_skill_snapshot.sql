-- 실행에 실제로 실린 Skill의 신원을 Task 행에 고정한다
-- (로드맵 `#65` 게이트 2 — revision 재현).
--
-- `skills_required`는 **이름 목록**이다. 이름은 그때 무엇이 실행됐는지를
-- 말해 주지 않는다 — 같은 `security-audit`라도 어제의 본문과 오늘의 본문이
-- 다르면 다른 실행이고, 파일은 오케스트레이터의 디스크에 있어 언제든
-- 바뀐다. 그래서 `#65`가 "revision 재현"을 게이트로 둔 것이고, 정본
-- [하네스 구성](../../../docs/architecture/agents/harness-composition.md)이
-- "필수 Skill은 시작 전에 revision/hash까지 **고정**한다"고 적은 것이다.
--
-- 담는 것은 조립 시점에 실제로 주입된 본문의 sha256이다. 본문 자체를 담지
-- 않는 이유가 둘이다: 프롬프트 본문은 `tasks.prompt`에 이미 있고(중복),
-- 무엇보다 Skill 본문이 커지면 Task 행이 그만큼 커진다. 해시는 "같은가"를
-- 답하기에 충분하고, "무엇이었는가"는 그 해시를 가진 파일을 찾는 문제다.
--
-- **JSONB인 이유**는 Skill이 0..N개이고 각각 이름·해시·길이를 갖기 때문이다.
-- 별도 테이블을 만들지 않은 것은 `041`이 `task_attempts`를 만들지 않은 것과
-- 같은 근거다 — 무재시도 정책(`#97`) 아래에서 Task당 실행이 하나뿐이라
-- 이 값은 그 행에 1:1로 얹힌다.
--
-- **NULL을 빈 배열로 접지 않는다.** `NULL`은 "조립 기록이 없다"(044 이전 행,
-- 그리고 dispatch된 적 없는 행)이고 `[]`는 "조립했고 Skill이 없었다"이다.
-- 둘은 다른 사실이며, 접으면 게이트 2가 답하려는 질문("그때 무엇이
-- 실행됐는가")에 대해 거짓을 만든다.
ALTER TABLE tasks ADD COLUMN skill_snapshot JSONB;
