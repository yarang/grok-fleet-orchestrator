-- 증거"라는 이 컬럼의 뜻이 첫 행부터 거짓이 된다 — `042`가 증명 가능한
-- 상한을 채운 것과 달리, 여기서 채울 값은 **다른 사실**이지 같은 사실의
-- 느슨한 추정이 아니다.
